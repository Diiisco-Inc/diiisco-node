// Public surface
// ---------------------------------------------------------------------------

export type WebAssetSource = 'embedded' | 'directory' | 'none';

export interface WebAssets {
  source: WebAssetSource;
  /** How many assets are available (embedded builds only; 0 for a directory). */
  count: number;
  /** Human-readable origin, for the startup log line. */
  origin: string;
  /** Resolve a request path, or `null` when this build cannot serve it. */
  get(path: string): WebAsset | null;
  /** The SPA shell, served for every HTML route. */
  index(): WebAsset | null;
}

/**
 * `candidateDirs` are on-disk web roots to try, most specific first. The first
 * one containing an `index.html` wins; only when none does — which is always
 * the case inside a compiled binary — does the embedded manifest take over.
 * Directory first so the existing tsup/`dist/web` behaviour is untouched and a
 * local `npm run build:web` shows up without regenerating the manifest.
 */
export function resolveWebAssets(candidateDirs: (string | null | undefined)[]): WebAssets {
  for (const candidate of candidateDirs) {
    if (!candidate) continue;
    let usable = false;
    try {
      usable = statSync(join(candidate, 'index.html')).isFile();
    } catch {
      usable = false;
    }
    if (!usable) continue;
    const dir = candidate;
    return {
      source: 'directory',
      count: 0,
      origin: dir,
      get: (path) => fromDirectory(dir, path),
      index: () => fromDirectory(dir, '/index.html'),
    };
  }

  if (manifestPaths.length > 0) {
    return {
      source: 'embedded',
      count: manifestPaths.length,
      origin: 'embedded manifest',
      get: (path) => fromManifest(path),
      index: () => fromManifest('/index.html'),
    };
  }

  return {
    source: 'none',
    count: 0,
    origin: 'none',
    get: () => null,
    index: () => null,
  };
}
