#!/usr/bin/env node
/**
 * Turn the status-pages build (`dist/web`, produced by `npm run build:web`)
 * into `src/api/webManifest.generated.json` — an in-memory manifest the node
 * serves the pages from.
 *
 *   node scripts/build-web-manifest.mjs            # from dist/web
 *   node scripts/build-web-manifest.mjs --clear    # back to an empty manifest
 *   node scripts/build-web-manifest.mjs --check    # non-zero if it is stale
 *
 * ## Why a manifest instead of `express.static(<dir>)`
 *
 * `bun build --compile` embeds *files*, and Bun's standalone filesystem has no
 * **directories**: `existsSync('/$bunfs/root/web')` is false and `readdirSync`
 * throws. A binary that embedded the assets but kept the directory mount would
 * serve an `index.html` whose hashed JS and CSS 404 — strictly worse than the
 * fallback shell. Serving from a manifest never stats a directory, so the
 * compiled binary and a source checkout behave identically.
 *
 * ## Why the manifest is committed
 *
 * It is a build artifact in source control, like a lockfile. The alternative —
 * generating it during the binary build — means every `bun build --compile`
 * needs a working `web/` npm install first, and a release built without one
 * would silently ship the fallback shell. Committing it makes the compiled
 * binary self-contained from a fresh clone and makes a change to the status
 * pages visible in review.
 *
 * **So: after changing anything under `web/`, run `npm run build:web` and
 * commit the regenerated manifest with your change.**
 *
 * Text assets are stored verbatim (JSON escaping costs a few percent); binary
 * assets are base64. Every entry carries the content type and a content-hash
 * ETag computed here, so serving is a map lookup and two header writes.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const webDist = join(root, 'dist', 'web');
const output = join(root, 'src', 'api', 'webManifest.generated.json');

const args = process.argv.slice(2);
const flag = (name) => args.includes(`--${name}`);

/** request extension → content type. Anything unlisted is served as a download. */
const CONTENT_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.map': 'application/json; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.webmanifest': 'application/manifest+json',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif',
  '.webp': 'image/webp',
  '.avif': 'image/avif',
  '.ico': 'image/x-icon',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.ttf': 'font/ttf',
  '.otf': 'font/otf',
  '.eot': 'application/vnd.ms-fontobject',
};

/** Types stored as UTF-8 text rather than base64. */
const TEXT_TYPES = new Set(['.html', '.js', '.mjs', '.css', '.json', '.map', '.txt', '.svg', '.webmanifest']);

function extensionOf(name) {
  const dot = name.lastIndexOf('.');
  return dot === -1 ? '' : name.slice(dot).toLowerCase();
}

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.isFile()) out.push(full);
  }
  return out;
}

function build() {
  if (!existsSync(webDist) || !existsSync(join(webDist, 'index.html'))) {
    return { files: {}, generatedFrom: null };
  }

  const files = {};
  for (const file of walk(webDist).sort()) {
    const requestPath = `/${relative(webDist, file).split(sep).join(posix.sep)}`;
    const extension = extensionOf(file);
    const bytes = readFileSync(file);
    const text = TEXT_TYPES.has(extension);

    files[requestPath] = {
      contentType: CONTENT_TYPES[extension] ?? 'application/octet-stream',
      encoding: text ? 'utf8' : 'base64',
      // Content hash, so a rebuilt asset always invalidates.
      etag: `"${createHash('sha256').update(bytes).digest('hex').slice(0, 32)}"`,
      bytes: bytes.length,
      content: text ? bytes.toString('utf8') : bytes.toString('base64'),
    };
  }

  return { files, generatedFrom: 'dist/web' };
}

function serialise(manifest) {
  return `${JSON.stringify(
    {
      // Deliberately no timestamp: the manifest must be reproducible so a
      // rebuild with no asset change produces no diff.
      $comment:
        'GENERATED by scripts/build-web-manifest.mjs from dist/web — do not edit. Run `npm run build:web` after changing anything under web/.',
      generatedFrom: manifest.generatedFrom,
      files: manifest.files,
    },
    null,
    2
  )}\n`;
}

const manifest = flag('clear') ? { files: {}, generatedFrom: null } : build();
const serialised = serialise(manifest);
const count = Object.keys(manifest.files).length;

if (flag('check')) {
  const current = existsSync(output) ? readFileSync(output, 'utf8') : '';
  if (current !== serialised) {
    console.error('build-web-manifest: src/api/webManifest.generated.json is stale — run `npm run build:web`.');
    process.exit(1);
  }
  console.log(`build-web-manifest: manifest is up to date (${count} file${count === 1 ? '' : 's'}).`);
  process.exit(0);
}

if (count === 0 && !flag('clear')) {
  console.warn('build-web-manifest: no dist/web build found — writing an empty manifest.');
  console.warn('                    the node will serve the built-in fallback shell.');
}

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, serialised, 'utf8');

const total = Object.values(manifest.files).reduce((sum, f) => sum + f.bytes, 0);
console.log(
  `build-web-manifest: ${count} file${count === 1 ? '' : 's'}, ${(total / 1024).toFixed(1)} KB → ` +
    `${relative(root, output)} (${(statSync(output).size / 1024).toFixed(1)} KB)`
);
